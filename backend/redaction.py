"""Redaction-фильтр (152-ФЗ, медицинский контекст): вычищает диагнозы и
чувствительные медицинские формулировки на «[скрыто]» ПЕРЕД записью в БД.

Важно: список — только клинические ДИАГНОЗЫ, не поводы обращения и не услуги
(«чистка», «кариес», «имплант» — остаются, иначе сломаем маршрутизацию и
детект услуги). Диагнозы ставит врач, а не карточка лида.
"""

from __future__ import annotations

import re

MASK = "[скрыто]"

# Диагнозы и явные медицинские состояния. «кариес» намеренно НЕ включён —
# это повод обращения/услуга, а не диагноз в смысле карточки.
_DIAGNOSIS_PATTERNS = [
    r"пульпит\w*",
    r"периодонтит\w*",
    r"периостит\w*",
    r"пародонтит\w*",
    r"пародонтоз\w*",
    r"гингивит\w*",
    r"стоматит\w*",
    r"кист[аыуеой]\w*",
    r"гранулем\w*",
    r"гранулём\w*",
    r"абсцесс\w*",
    r"остеомиелит\w*",
    r"невралги\w*",
    r"опухол\w*",
    r"новообразован\w*",
    r"онколог\w*",
    r"\bрак\b",
    r"диагноз\w*",
]
_RE = re.compile("|".join(_DIAGNOSIS_PATTERNS), re.IGNORECASE)


def redact(text: str | None) -> str | None:
    """Заменяет диагнозы на [скрыто]. None/пустое — как есть."""
    if not text:
        return text
    return _RE.sub(MASK, text)


def has_diagnosis(text: str | None) -> bool:
    return bool(text) and bool(_RE.search(text))
