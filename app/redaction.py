"""Редактирование медицинских и чувствительных данных ДО записи в БД (152-ФЗ).

Применяется в db.add_message к репликам пациента: диагнозы и системные болезни
заменяются на «[скрыто]». Анне они не нужны (её правила запрещают обсуждать
лечение), а в карточке лида и transcript их быть не должно.

Осознанно НЕ трогаем слова, нужные для записи: «кариес», «имплант», «чистка»,
«коронка», «пломба», «зуб», «болит» — иначе сломаем распознавание услуги.
"""

from __future__ import annotations

import re

PLACEHOLDER = "[скрыто]"

# Конкретные диагнозы и системные болезни/состояния (не услуги).
_SENSITIVE = [
    r"пульпит\w*", r"периодонтит\w*", r"пародонтит\w*", r"гингивит\w*",
    r"кист[аыуой]\w*", r"гранулем\w*", r"абсцесс\w*", r"остеомиелит\w*",
    r"флюс\w*", r"свищ\w*", r"неврит\w*", r"невралги\w*",
    r"вич\b", r"спид\w*", r"гепатит\w*", r"туберкулёз\w*", r"туберкулез\w*",
    r"сахарн\w*\s+диабет\w*", r"диабет\w*", r"онкологи\w*", r"\bрак\b",
    r"эпилепси\w*", r"астм\w*", r"гипертони\w*", r"аритми\w*",
    r"беременн\w*", r"вич-инф\w*",
    r"аллерги\w*\s+на\s+\w+",
    # Явные конструкции «диагноз …», «поставили …», «болею …»
    r"диагноз[^.,;!?\n]{0,40}",
]
_RE = re.compile("|".join(_SENSITIVE), re.IGNORECASE)


def redact(text: str) -> str:
    """Заменяет чувствительные фрагменты на «[скрыто]». Идемпотентно."""
    if not text:
        return text
    return _RE.sub(PLACEHOLDER, text)


def contains_sensitive(text: str) -> bool:
    return bool(_RE.search(text or ""))


# --- Обезличивание для отправки в GigaChat (соглашение: ПДн не передаём) -----

# Телефоноподобные последовательности (≥7 цифр с разделителями) → «[телефон]».
_LLM_PHONE_RE = re.compile(r"(?:\+?[78][\s\-()]*)?(?:\d[\s\-()]{0,2}){6,}\d")

# Явные представления имени: «меня зовут X», «это X», «я X» — лучший-эффорт.
_NAME_INTRO_RE = re.compile(
    r"(меня\s+зовут|мо[её]\s+имя|это|я)\s+([А-ЯЁ][а-яё]+)", re.IGNORECASE
)


def anonymize_for_llm(text: str, name: str | None = None) -> str:
    """Готовит реплику к отправке в GigaChat: вырезает ПДн (телефон, имя,
    диагнозы). ФИО/номер остаются ТОЛЬКО в локальной SQLite, в модель не уходят.

    - диагнозы/болезни → «[скрыто]» (как при хранении, идемпотентно);
    - любые телефоноподобные последовательности → «[телефон]»;
    - известное имя пациента (по границе слова) → «пациент»;
    - конструкции «меня зовут X» → «меня зовут пациент» (на случай раннего имени).
    """
    if not text:
        return text
    t = redact(text)
    t = _LLM_PHONE_RE.sub("[телефон]", t)
    if name:
        t = re.sub(rf"\b{re.escape(name)}\b", "пациент", t, flags=re.IGNORECASE)
    t = _NAME_INTRO_RE.sub(lambda m: f"{m.group(1)} пациент", t)
    return t


def anonymize_history(history: list[dict], name: str | None = None) -> list[dict]:
    """Обезличивает все реплики истории перед передачей в GigaChat."""
    return [{**m, "content": anonymize_for_llm(m.get("content", ""), name)} for m in history]
