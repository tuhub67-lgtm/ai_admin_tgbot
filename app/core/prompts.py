def build_system_prompt(clinic: Clinic, step: str) -> str:
    base = ANNA_SYSTEM_PROMPT.format(
        name=clinic.name,
        city=clinic.city,
        address=clinic.address,
        work_hours=clinic.work_hours,
        tone=clinic.tone,
        phone_display=clinic.phone_display,
        services_list=clinic.services_list_text(),
    )
    goal = STEP_GOALS.get(step)
    if goal:
        base += f"\n\nТЕКУЩАЯ ЦЕЛЬ ШАГА: {goal}"
    return base


def fallback_reply(step: str, clinic: Clinic) -> str:
    template = FALLBACK_REPLIES.get(step, FALLBACK_REPLIES["SERVICE"])
    return template.format(name=clinic.name, phone_display=clinic.phone_display)
